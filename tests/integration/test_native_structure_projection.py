"""Native XML roundtrip with two weapon-specific trees and free amulet grants."""

import hashlib

import pytest

from pok.artifacts.store import read_build_blob, record_immutable_build
from pok.engine.pob_documents import load_document_measurement, measure_document
from pok.pob.buildxml import BuildSpec, GemSpec, ItemSpec, SkillGroupSpec, spec_from_dict, to_xml
from pok.pob.daemon import PobDaemon
from pok.pob.restore import spec_from_pob_xml
from pok.pob.versions import find_luajit, resolve_snapshot


def ready():
    try:
        find_luajit()
        resolve_snapshot()
    except (FileNotFoundError, RuntimeError):
        return False
    return True


pytestmark = pytest.mark.skipif(not ready(), reason="LuaJIT or pinned PoB unavailable")


@pytest.mark.parametrize("second", ["false", "true"])
def test_native_weapon_specific_nodes_and_selector_survive_projection(second):
    # Independent raw source, not generated by the serializer under test.
    xml = f'''<PathOfBuilding2>
<Build className="Sorceress" ascendClassName="Stormweaver" level="90"
mainSocketGroup="1" targetVersion="0_1"/>
<Tree activeSpec="1"><Spec treeVersion="0_5" classId="7" classInternalId="7"
ascendClassId="1" ascendancyInternalId="Sorceress1" nodes="4739,22419">
<WeaponSet1 nodes="4739"/><WeaponSet2 nodes="22419"/></Spec></Tree>
<Skills activeSkillSet="1"><SkillSet id="1"><Skill enabled="true" mainActiveSkill="1">
<Gem gemId="Metadata/Items/Gems/SkillGemSpark" nameSpec="Spark" level="20"
quality="0" enabled="true" enableGlobal1="true" enableGlobal2="true"/>
</Skill></SkillSet></Skills>
<Items activeItemSet="1"><ItemSet id="1" useSecondWeaponSet="{second}"/></Items>
<Config/></PathOfBuilding2>'''
    restored = spec_from_pob_xml(xml, assume_first_stat_set=False)
    projected = to_xml(spec_from_dict(restored.spec))
    with PobDaemon() as daemon:
        baseline = daemon.compute(xml)
        measured = daemon.compute(projected)
    assert measured.stats == baseline.stats
    assert restored.spec["weapon_set"] == (2 if second == "true" else 1)
    assert restored.spec["weapon_set_1_nodes"] == [4739]
    assert restored.spec["weapon_set_2_nodes"] == [22419]


def test_native_document_attaches_existing_free_amulet_fact_to_receipt(tmp_path):
    xml = to_xml(
        BuildSpec(
            class_name="Sorceress",
            ascendancy="Sorceress1",
            level=90,
            skills=(
                SkillGroupSpec(
                    gems=(
                        GemSpec(
                            gem_id="Metadata/Items/Gems/SkillGemSpark",
                            name="Spark",
                            stat_set_index=1,
                        ),
                    )
                ),
            ),
            items=(
                ItemSpec(
                    slot="Amulet",
                    text=(
                        "Rarity: RARE\nNative Test Amulet\nAbsent Amulet\n"
                        "Grants Skill: Level 20 Eternal Rage"
                    ),
                ),
            ),
        )
    )
    saved = record_immutable_build("grant-source", {"input.xml": xml.encode()}, {}, root=tmp_path)
    reference = {
        "artifact_id": "grant-source",
        "name": "input.xml",
        "sha256": saved["files"]["input.xml"]["sha256"],
    }
    result = measure_document(reference, stats=["SpiritUnreserved"], use_cache=False, root=tmp_path)
    stored = load_document_measurement(
        result["document_measurement_ref"], reference, root=tmp_path
    )["measurement"]
    fact = result["granted_skill_instances"][0]
    assert fact["skill"] == "Eternal Rage"
    assert fact["granted_instance_spirit_reservation"] == 0
    assert stored["granted_skill_instances"] == result["granted_skill_instances"]
    assert stored["stats"]["SpiritUnreserved"] == result["stats"]["SpiritUnreserved"]
    assert result["xml_revision"] == "sha256:" + hashlib.sha256(xml.encode()).hexdigest()
    raw = read_build_blob("grant-source", "input.xml", reference["sha256"], root=tmp_path)
    assert raw == xml.encode()

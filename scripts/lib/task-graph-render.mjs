// Workflow Governance Kit — task graph Mermaid renderer.
//
// Shared by the `task graph` CLI verb (which calls `renderTaskGraphTo` /
// `checkTaskGraphInSync`) and by scripts/workflow-guard.mjs (which calls
// `checkTaskGraphInSync` to fail the precommit gate when tasks/state.json
// has drifted from its rendered Mermaid view).
//
// The render contract is documented in `docs/TASK-GRAPH.md` §6.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { SchemaError, validateState } from './task-graph-schema.mjs';

export const TASK_STATE_REL = 'tasks/state.json';
export const TASK_RENDER_REL = 'docs/TASK-GRAPH-RENDER.md';

function escapeMermaidLabel(value) {
  // Mermaid `["label"]` nodes treat several characters as syntax or as raw HTML
  // when rendered by GitHub / VS Code preview. We strip or substitute the
  // characters that can break the label or surface unexpected markup:
  //   "          -> escaped (\")          : preserves the quote in the rendered label
  //   newline    -> single space          : Mermaid does not handle multi-line labels well
  //   [ ]        -> ( )                   : avoids closing the node-label syntax mid-string
  //   < >        -> &lt; / &gt;           : prevents raw HTML/script tags reaching the renderer
  //   `          -> '                     : avoids opening a fenced code span inside the label
  return String(value)
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, ' ')
    .replace(/[\[\]<>`]/g, (c) => ({ '[': '(', ']': ')', '<': '&lt;', '>': '&gt;', '`': "'" }[c]));
}

function nodeId(id) {
  return id.replace(/[^a-zA-Z0-9_]/g, '_');
}

export function formatMermaid(state) {
  validateState(state);
  const tasks = Object.values(state.tasks);
  const lanes = [...new Set(tasks.map((t) => t.lane))].sort();
  const lines = [];
  lines.push('# Task Graph (auto-generated)');
  lines.push('');
  lines.push(`Source: \`${TASK_STATE_REL}\`. Do not edit this file by hand; rerun \`workflow-governance task graph\` after mutations.`);
  lines.push('');
  if (tasks.length === 0) {
    lines.push('No tasks.');
    lines.push('');
    return lines.join('\n');
  }
  lines.push('```mermaid');
  lines.push('flowchart TD');

  for (const lane of lanes) {
    const laneTasks = tasks.filter((t) => t.lane === lane).sort((a, b) => a.id.localeCompare(b.id));
    if (laneTasks.length > 1) {
      lines.push(`  subgraph ${nodeId(lane)} ["${escapeMermaidLabel(lane)}"]`);
      for (const t of laneTasks) {
        lines.push(`    ${nodeId(t.id)}["${escapeMermaidLabel(t.id)}<br/>${escapeMermaidLabel(t.title)}<br/>${t.status}"]`);
      }
      lines.push('  end');
    } else {
      const t = laneTasks[0];
      lines.push(`  ${nodeId(t.id)}["${escapeMermaidLabel(t.id)}<br/>${escapeMermaidLabel(t.title)}<br/>${t.status}"]`);
    }
  }

  // Sort tasks for deterministic edge order across runs.
  const sortedTasks = [...tasks].sort((a, b) => a.id.localeCompare(b.id));
  for (const t of sortedTasks) {
    for (const dep of [...t.dependsOn].sort()) {
      lines.push(`  ${nodeId(dep)} --> ${nodeId(t.id)}`);
    }
  }
  lines.push('```');
  lines.push('');
  return lines.join('\n');
}

export function renderTaskGraphTo(renderPath, state) {
  const text = formatMermaid(state);
  const dir = dirname(renderPath);
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  writeFileSync(renderPath, text, 'utf8');
  return text;
}

export function checkTaskGraphInSync(renderPath, state) {
  // Returns void on success; throws SchemaError(code='render-missing'|'render-stale')
  // on mismatch. Caller is expected to translate the error into the appropriate
  // exit code or guard severity.
  const expected = formatMermaid(state);
  if (!existsSync(renderPath)) {
    throw new SchemaError(
      `render check failed: ${renderPath} does not exist. Run \`workflow-governance task graph\` (or any task mutation) to (re)create it.`,
      { code: 'render-missing' },
    );
  }
  // Normalize CRLF on the on-disk side: on Windows with default
  // `core.autocrlf=true`, a git checkout may rewrite \n to \r\n even though
  // the canonical content is LF-only. Normalizing before compare keeps the
  // round-trip check robust on every platform without requiring every
  // consumer to pin .gitattributes.
  const onDisk = readFileSync(renderPath, 'utf8').replace(/\r\n/g, '\n');
  if (onDisk !== expected) {
    throw new SchemaError(
      `render check failed: ${renderPath} is out of sync with ${TASK_STATE_REL}. Run \`workflow-governance task graph\` to refresh it.`,
      { code: 'render-stale' },
    );
  }
}
